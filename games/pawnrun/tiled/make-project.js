// Writes tiled/pawnrun.tiled-project (marker classes, enums, automapping rules). Re-runnable: node tiled/make-project.js
const fs = require('fs'), path = require('path');
let id = 0;
const en = (name, values) => ({ id: ++id, name, type: 'enum', storageType: 'string', values, valuesAsFlags: false });
const str = (name, value = '') => ({ name, type: 'string', value });
const enm = (name, type, value) => ({ name, type: 'string', propertyType: type, value });
const cls = (name, color, members, useAs = ['property', 'map', 'object', 'tile']) =>
  ({ id: ++id, name, type: 'class', color, members, useAs, drawFill: true });
const types = [
  en('lootKind', ['duck', 'weapon', 'dynamite', 'bomb', 'gold', 'meat', 'random']),
  en('secretKind', ['tree', 'rock', 'stones']),
  en('chunkKind', ['landmark', 'set']),
  cls('entrance', '#ff40c0ff', []),
  cls('enemy', '#ffff4040', [str('kind'), { name: 'count', type: 'int', value: 1 }]),
  cls('camp', '#ffff8040', [str('kind')]),
  cls('boss', '#ffc000c0', [str('kind')]),
  cls('loot', '#ffffd020', [enm('kind', 'lootKind', 'random'), { name: 'n', type: 'int', value: 1 }, str('weapon'), { name: 'tier', type: 'int', value: 0 }]),   // weapon/tier: only for kind weapon (axe, hammer, pickaxe, knife; tier 0-3)
  cls('secret', '#ff20c040', [enm('kind', 'secretKind', 'tree')]),
  cls('stepstone', '#ff40a0ff', [], ['property', 'object', 'tile']),   // a Water Rock in the water that feet can stand on (they must overlap to form a path)
  cls('npc', '#ffffffff', [str('role')]),
  cls('shop', '#ffe0a060', [str('shop')]),
  cls('gate', '#ffa0a0a0', []),
  cls('washup', '#ff4080ff', []),
  cls('spawn', '#ff40ff40', []),
  cls('chunk', '#ffff80ff', [enm('kind', 'chunkKind', 'landmark'), str('biomes'),
    { name: 'minIsland', type: 'int', value: 1 }, { name: 'weight', type: 'float', value: 1 }, { name: 'mirror', type: 'bool', value: false }], ['property', 'map']),
  // doors and interiors (src/scenes/Interior.js): a `door` rect on an outdoor map names the interior map it opens;
  // inside, `floor` rects are walkable, `block` rects cut furniture out of them, `spawn` is where you appear, `exit` leaves
  cls('door', '#ffff8000', [str('interior')], ['property', 'object']),
  cls('floor', '#8040ff40', [], ['property', 'object']),
  cls('block', '#80ff4040', [], ['property', 'object']),
  cls('exit', '#ff4080ff', [], ['property', 'object']),
  cls('interior', '#ffa0e0ff', [], ['property', 'map']),
];
const project = {
  automappingRulesFile: 'rules.txt', // rules.txt is generated by make-rules.js
  commands: [], compatibilityVersion: 1120, extensionsPath: 'extensions',
  folders: ['../maps'], propertyTypes: types,
};
fs.writeFileSync(path.join(__dirname, 'pawnrun.tiled-project'), JSON.stringify(project, null, 1) + '\n');
console.log('project written,', types.length, 'types');
