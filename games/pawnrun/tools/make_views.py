def frame(art, shadow):
    f = shadow.copy()
    for dy, row in enumerate(art.strip("\n").split("\n")):
        for dx, ch in enumerate(row):
            if ch in LEGEND:
                f[ORIGIN[1] + dy, ORIGIN[0] + dx] = (*LEGEND[ch], 255)
    return f


